function generateAssemblyFirmware(nodes: AssemblyNode[]): string {
  const animated = nodes.filter(
    (n) => n.automation.enabled && n.automation.mode !== "static",
  );
  const targets = animated.length > 0 ? animated : nodes;

  const lines: string[] = [
    "// AUTO-GENERATED BY 1/0 iAGNT - XR ASSEMBLY STUDIO",
    "// Control multi-eje de rotación y traslación para prototipado",
    "#include <Servo.h>",
    "",
  ];

  targets.forEach((n, idx) => {
    const safeId = n.id.replace(/[^a-zA-Z0-9]/g, "_").slice(0, 12);
    const pin = n.suggestedPin?.replace(/\D/g, "") || String(3 + idx);
    lines.push(`Servo axis_${safeId}; // ${n.label} [${n.automation.mode.toUpperCase()} ${n.automation.axis.toUpperCase()}] Pin ${pin}`);
  });

  lines.push("", "unsigned long startMs = 0;", "", "void setup() {", "  Serial.begin(115200);");
  targets.forEach((n, idx) => {
    const safeId = n.id.replace(/[^a-zA-Z0-9]/g, "_").slice(0, 12);
    const pin = n.suggestedPin?.replace(/\D/g, "") || String(3 + idx);
    lines.push(`  axis_${safeId}.attach(${pin});`);
  });
  lines.push('  startMs = millis();', '  Serial.println("XR_KINEMATICS_READY");', "}", "", "void loop() {", "  float t = (millis() - startMs) / 1000.0;");

  targets.forEach((n) => {
    const safeId = n.id.replace(/[^a-zA-Z0-9]/g, "_").slice(0, 12);
    const a = n.automation;
    const dir = a.inverted ? "-1.0" : "1.0";
    if (a.mode === "oscillate") {
      lines.push(
        `  int deg_${safeId} = constrain(90 + (int)(sin(t * ${a.speed.toFixed(2)} + ${a.phase.toFixed(2)}) * ${a.amplitude.toFixed(1)} * ${dir}), 0, 180);`,
        `  axis_${safeId}.write(deg_${safeId});`,
      );
    } else if (a.mode === "rotate" || a.mode === "helical") {
      lines.push(
        `  int deg_${safeId} = ((int)(t * ${a.speed.toFixed(2)} * 57.2958) % 180);`,
        `  axis_${safeId}.write(deg_${safeId});`,
      );
    } else if (a.mode === "translate") {
      lines.push(
        `  int pos_${safeId} = constrain(90 + (int)(sin(t * ${a.speed.toFixed(2)} + ${a.phase.toFixed(2)}) * 60 * ${dir}), 0, 180);`,
        `  axis_${safeId}.write(pos_${safeId});`,
      );
    }
  });

  lines.push("  delay(16);", "}");
  return lines.join("\n");
}

/**
 * Sincroniza el renderer WebGL con transparencia y soporte WebXR nativo.
 */
function SceneEnvironmentBridge({
  transparentBg,
  xrTrigger,
  onXrStatus,
  vrStereo,
}: {
  transparentBg: boolean;
  xrTrigger: { mode: "ar" | "vr" | null; seq: number };
  onXrStatus: (msg: string) => void;
  vrStereo: boolean;
}) {
  const { gl, scene, camera, size } = useThree();

  useEffect(() => {
    gl.setClearColor(0x000000, transparentBg ? 0 : 1);
    gl.xr.enabled = true;
  }, [gl, transparentBg]);

  // Efecto estereoscópico VR dual-eye cuando vrStereo está activo sin casco WebXR
  useFrame(() => {
    if (!vrStereo || gl.xr.isPresenting) return;
    const w = size.width;
    const h = size.height;
    const halfW = Math.floor(w / 2);
    const cam = camera as THREE.PerspectiveCamera;
    const ipd = 0.064;
    const savedX = cam.position.x;

    gl.setScissorTest(true);

    // Ojo Izquierdo
    cam.aspect = halfW / h;
    cam.updateProjectionMatrix();
    cam.position.x = savedX - ipd / 2;
    gl.setViewport(0, 0, halfW, h);
    gl.setScissor(0, 0, halfW, h);
    gl.render(scene, cam);

    // Ojo Derecho
    cam.position.x = savedX + ipd / 2;
    gl.setViewport(halfW, 0, w - halfW, h);
    gl.setScissor(halfW, 0, w - halfW, h);
    gl.render(scene, cam);

    // Restaurar
    cam.position.x = savedX;
    cam.aspect = w / h;
    cam.updateProjectionMatrix();
    gl.setViewport(0, 0, w, h);
    gl.setScissor(0, 0, w, h);
    gl.setScissorTest(false);
  }, vrStereo ? 1 : 0);

  useEffect(() => {
    if (!xrTrigger.mode || xrTrigger.seq === 0) return;
    const navXr = (navigator as any).xr;
    if (!navXr) {
      onXrStatus(
        "WebXR nativo no disponible en este navegador/iframe. Usando modo XR/VR integrado.",
      );
      return;
    }

    const sessionMode =
      xrTrigger.mode === "ar" ? "immersive-ar" : "immersive-vr";

    navXr
      .isSessionSupported(sessionMode)
      .then((supported: boolean) => {
        if (!supported) {
          onXrStatus(
            `Sesión ${sessionMode} no soportada en este dispositivo. Activo en vista integrada.`,
          );
          return;
        }
        return navXr
          .requestSession(sessionMode, {
            optionalFeatures: ["local-floor", "bounded-floor", "hit-test"],
          })
          .then((session: any) => {
            gl.xr.setSession(session);
            onXrStatus(`Sesión ${sessionMode} iniciada correctamente.`);
            session.addEventListener("end", () => {
              onXrStatus("Sesión WebXR finalizada.");
            });
          });
      })
      .catch((err: any) => {
        onXrStatus(
          `WebXR: ${err?.message || "No se pudo abrir sesión inmersiva"}. Vista integrada activa.`,
        );
      });
  }, [xrTrigger, gl, onXrStatus]);

  return null;
}

/**
 * Nodo jerárquico con animación de ejes de rotación / traslación y soporte TransformControls.
 */
function AutomatedAssemblyNode({
  node,
  allNodes,
  selectedNodeId,
  connectMode,
  transformMode,
  isPlaying,
  globalSpeed,
  showAxisGuides,
  onSelect,
  onTransformEnd,
  onDragChange,
  onLiveTelemetry,
}: {
  node: AssemblyNode;
  allNodes: AssemblyNode[];
  selectedNodeId: string | null;
  connectMode: boolean;
  transformMode: "translate" | "rotate" | "scale";
  isPlaying: boolean;
  globalSpeed: number;
  showAxisGuides: boolean;
  onSelect: (id: string) => void;
  onTransformEnd: (id: string, group: THREE.Group) => void;
  onDragChange: (dragging: boolean) => void;
  onLiveTelemetry: (id: string, axisVal: number) => void;
}) {
  const anchorRef = useRef<THREE.Group>(null);
  const animatedRef = useRef<THREE.Group>(null);
  const clockAccum = useRef(0);
  const lastReport = useRef(0);

  const isSelected = selectedNodeId === node.id;
  const children = useMemo(
    () => allNodes.filter((n) => n.parentId === node.id),
    [allNodes, node.id],
  );

  // Reset kinematic offset when node returns to static
  useEffect(() => {
    if (animatedRef.current && (!node.automation.enabled || node.automation.mode === "static")) {
      animatedRef.current.position.set(0, 0, 0);
      animatedRef.current.rotation.set(0, 0, 0);
    }
  }, [node.automation.enabled, node.automation.mode]);

  useFrame((_, delta) => {
    const g = animatedRef.current;
    if (!g) return;
    const auto = node.automation;
    if (!auto.enabled || auto.mode === "static") return;

    if (isPlaying) {
      clockAccum.current += delta * auto.speed * globalSpeed;
    }

    const t = clockAccum.current + auto.phase;
    const dir = auto.inverted ? -1 : 1;
    let displayValue = 0;

    g.position.set(0, 0, 0);
    g.rotation.set(0, 0, 0);

    if (auto.mode === "rotate") {
      const angle = t * dir;
      g.rotation[auto.axis] = angle;
      displayValue = ((angle * 180) / Math.PI) % 360;
    } else if (auto.mode === "oscillate") {
      const rad = THREE.MathUtils.degToRad(auto.amplitude) * Math.sin(t) * dir;
      g.rotation[auto.axis] = rad;
      displayValue = THREE.MathUtils.radToDeg(rad);
    } else if (auto.mode === "translate") {
      const offset = Math.sin(t) * auto.amplitude * dir;
      g.position[auto.axis] = offset;
      displayValue = offset;
    } else if (auto.mode === "helical") {
      const rot = t * 1.6 * dir;
      const offset = Math.sin(t) * auto.amplitude * dir;
      g.rotation[auto.axis] = rot;
      g.position[auto.axis] = offset;
      displayValue = offset;
    }

    lastReport.current += delta;
    if (isSelected && lastReport.current > 0.12) {
      lastReport.current = 0;
      onLiveTelemetry(node.id, displayValue);
    }
  });

  const content = (
    <group
      ref={anchorRef}
      position={node.position}
      rotation={node.rotation}
      scale={node.scale}
      onClick={(e) => {
        e.stopPropagation();
        onSelect(node.id);
      }}
    >
      <group ref={animatedRef}>
        <CompositeStructureMesh node={node} isSelected={isSelected} />
        <AxisAutomationGuide
          automation={node.automation}
          visible={showAxisGuides && (isSelected || node.automation.mode !== "static")}
        />

        {isSelected && (
          <mesh rotation={[-Math.PI / 2, 0, 0]} position={[0, 0.02, 0]}>
            <ringGeometry args={[0.92, 1.02, 40]} />
            <meshBasicMaterial color="#3b82f6" side={THREE.DoubleSide} transparent opacity={0.85} />
          </mesh>
        )}

        {/* Recursivamente renderiza piezas acopladas sobre esta estructura */}
        {children.map((child) => (
          <AutomatedAssemblyNode
            key={child.id}
            node={child}
            allNodes={allNodes}
            selectedNodeId={selectedNodeId}
            connectMode={connectMode}
            transformMode={transformMode}
            isPlaying={isPlaying}
            globalSpeed={globalSpeed}
            showAxisGuides={showAxisGuides}
            onSelect={onSelect}
            onTransformEnd={onTransformEnd}
            onDragChange={onDragChange}
            onLiveTelemetry={onLiveTelemetry}
          />
        ))}
      </group>

      {isSelected && (
        <Html position={[0, 1.45, 0]} center zIndexRange={[50, 0]}>
          <div className="bg-slate-950/95 border border-blue-500/80 text-white px-2.5 py-1 rounded-md text-[11px] font-mono whitespace-nowrap shadow-lg flex items-center gap-2 pointer-events-none">
            <span className="w-2 h-2 rounded-full bg-blue-400" />
            <span>{node.label}</span>
          </div>
        </Html>
      )}
    </group>
  );

  if (isSelected && !connectMode && anchorRef.current) {
    return (
      <>
        {content}
        <TransformControls
          object={anchorRef.current}
          mode={transformMode}
          size={0.75}
          onMouseDown={() => onDragChange(true)}
          onMouseUp={() => {
            onDragChange(false);
            if (anchorRef.current) {
              onTransformEnd(node.id, anchorRef.current);
            }
          }}
        />
      </>
    );
  }

  return content;
}

